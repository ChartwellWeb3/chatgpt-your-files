"""Package canonical pricing sources for CLI and single-file Dashboard deployment.

Text packaging only: does not test, build, deploy, or read any credentials.
"""
from pathlib import Path
import re

performance = Path(__file__).resolve().parents[1]
root = performance.parents[1]
canonical = root / "lib" / "sitecore-pricing"
shared = performance / "supabase" / "functions" / "_shared" / "sitecore-pricing"
shared.mkdir(parents=True, exist_ok=True)
modules = []
for name in ("types", "config", "lock", "authoring", "edge-batch"):
    source = (canonical / f"{name}.ts").read_text(encoding="utf-8")
    source = source.replace('from "saxes"', 'from "npm:saxes@6.0.0"')
    source = source.replace('from "@supabase/supabase-js"', 'from "npm:@supabase/supabase-js@2.88.0"')
    source = source.replace('= process.env', '= Deno.env.toObject()')
    (shared / f"{name}.ts").write_text("// Generated by deploy/package_sitecore_pricing.py; edit lib/sitecore-pricing instead.\n" + source, encoding="utf-8")
    source = re.sub(r'^import .*? from "\./[^\"]+";\n', '', source, flags=re.M)
    source = re.sub(r'^import type .*?;\n', '', source, flags=re.M)
    modules.append(source)
entry = (performance / "supabase" / "functions" / "sitecore-pricing" / "index.ts").read_text(encoding="utf-8")
entry = re.sub(r'^import .*? from "\.\./_shared/[^\"]+";\n', '', entry, flags=re.M)
entry = entry.replace('import { createClient }', 'import { createClient, type SupabaseClient }')
(performance / "deploy" / "sitecore-pricing.dashboard.ts").write_text(
    "// Paste this ENTIRE file into the performance project's sitecore-pricing/index.ts.\n"
    "// Generated distribution. No credentials included. JWT verification must be OFF;\n"
    "// the handler verifies SITECORE_PRICING_DISPATCH_SECRET before any work.\n"
    + "\n".join(modules) + "\n" + entry, encoding="utf-8")
